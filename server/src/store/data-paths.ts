import { join } from 'node:path';

import { AppError } from '../domain/errors.js';
import { isValidAnalysisId, isValidImageId } from '../domain/ids.js';

/**
 * The persistence layout of the server, declared once.
 *
 * Every filesystem path the store touches is built here, so the on-disk shape —
 * `<dataDir>/analyses/<analysisId>/document.json` beside
 * `<dataDir>/analyses/<analysisId>/images/<imageId>` — exists in exactly one place and the
 * repository that performs the I/O never concatenates a segment of its own.
 *
 * This module is pure path arithmetic plus one consequence of the unauthenticated API: because an
 * analysis id is also a directory name and an image id is also a file name, and both arrive from a
 * URL, every builder matches the id against its pattern before any segment is joined. A crafted id
 * therefore cannot escape the data directory, and a rejected id is indistinguishable from a record
 * that was never stored: the same `404 NOT_FOUND` code, status and generic sentence, carrying
 * neither the id nor a filesystem path.
 *
 * Nothing here reads the environment, performs filesystem I/O, resolves a relative path or caches a
 * result. Every call recomputes from the `dataDir` it is given, so a second repository instance on
 * the same directory resolves byte-identical paths.
 */

/** Directory beneath the data directory that holds one directory per analysis. */
export const ANALYSES_DIR_NAME = 'analyses';

/** File, inside an analysis directory, that holds that analysis's document. */
export const DOCUMENT_FILE_NAME = 'document.json';

/** Directory, inside an analysis directory, that holds the bytes of that analysis's images. */
export const IMAGES_DIR_NAME = 'images';

/**
 * Suffix of the temporary file a document is written to before being renamed into place. The
 * rename happens inside the analysis directory, so a half-written document is never observable.
 */
const TEMP_FILE_SUFFIX = '.tmp';

/**
 * Shape of the machine-generated token that makes a temporary file name unique. The suffix is
 * generated by the repository (a `randomUUID()` per write) and never comes from a request, so a
 * value outside this shape is a programming error rather than a missing record.
 */
const TEMP_SUFFIX_PATTERN = /^[A-Za-z0-9-]{1,64}$/;

/**
 * Refuses anything that is not an analysis id this system generated.
 *
 * @throws {AppError} `404 NOT_FOUND`, with the shared sentence as its message: the response must
 *   not carry the rejected value or any path, so a caller cannot learn the layout by probing ids.
 */
function assertAnalysisId(analysisId: string): void {
  if (!isValidAnalysisId(analysisId)) {
    throw AppError.notFound();
  }
}

/**
 * Refuses anything that is not an image id this system generated, for the same reason and with the
 * same indistinguishable answer as {@link assertAnalysisId}.
 *
 * @throws {AppError} `404 NOT_FOUND`.
 */
function assertImageId(imageId: string): void {
  if (!isValidImageId(imageId)) {
    throw AppError.notFound();
  }
}

/**
 * Refuses a temporary-file suffix that is not a short alphanumeric-hyphen token.
 *
 * @throws {AppError} `500 INTERNAL_ERROR`, not `404`: the suffix is never caller input, so an
 *   unusable one is a defect in the writing code rather than an unknown record.
 */
function assertTempSuffix(uniqueSuffix: string): void {
  if (typeof uniqueSuffix !== 'string' || !TEMP_SUFFIX_PATTERN.test(uniqueSuffix)) {
    throw AppError.internal(
      'documentTempPath requires a machine-generated suffix matching /^[A-Za-z0-9-]{1,64}$/',
    );
  }
}

/**
 * The directory that holds one directory per analysis: `<dataDir>/analyses`.
 *
 * Creating it is the repository's work, since this module never touches the filesystem, so the path
 * is returned whether or not the directory exists yet.
 */
export function analysesRoot(dataDir: string): string {
  return join(dataDir, ANALYSES_DIR_NAME);
}

/**
 * The directory of one analysis, which holds its document and its images directory.
 *
 * @throws {AppError} `404 NOT_FOUND` when `analysisId` is not an id this system generated, so a
 *   crafted id never becomes a directory segment.
 */
export function analysisDir(dataDir: string, analysisId: string): string {
  assertAnalysisId(analysisId);
  return join(analysesRoot(dataDir), analysisId);
}

/**
 * The document of one analysis: `<analysisDir>/document.json`.
 *
 * @throws {AppError} `404 NOT_FOUND` when `analysisId` is not an id this system generated. The
 *   guard runs here as well as inside {@link analysisDir} so this builder refuses a bad id before
 *   composing anything, whatever its callee grows into.
 */
export function documentPath(dataDir: string, analysisId: string): string {
  assertAnalysisId(analysisId);
  return join(analysisDir(dataDir, analysisId), DOCUMENT_FILE_NAME);
}

/**
 * The directory holding the bytes of one analysis's images: `<analysisDir>/images`.
 *
 * @throws {AppError} `404 NOT_FOUND` when `analysisId` is not an id this system generated.
 */
export function imagesDir(dataDir: string, analysisId: string): string {
  assertAnalysisId(analysisId);
  return join(analysisDir(dataDir, analysisId), IMAGES_DIR_NAME);
}

/**
 * The stored bytes of one image: `<imagesDir>/<imageId>`, the image id also being its file name.
 *
 * The analysis id is checked first, so a submission cannot reach another analysis's directory even
 * when its own image id is well formed.
 *
 * @throws {AppError} `404 NOT_FOUND` when either id is not one this system generated.
 */
export function imagePath(dataDir: string, analysisId: string, imageId: string): string {
  assertAnalysisId(analysisId);
  assertImageId(imageId);
  return join(imagesDir(dataDir, analysisId), imageId);
}

/**
 * The temporary file a document is written to before being renamed into place, in the analysis
 * directory itself so the rename cannot cross a filesystem boundary: `document.json.<suffix>.tmp`.
 *
 * The suffix is generated by the writer — a `randomUUID()` per write — so two concurrent
 * submissions of the same analysis id cannot scribble over each other's partial document.
 *
 * @throws {AppError} `404 NOT_FOUND` for an id this system did not generate, and
 *   `500 INTERNAL_ERROR` for a suffix that is not a short alphanumeric-hyphen token, which is a
 *   defect in the calling code rather than an unknown record.
 */
export function documentTempPath(
  dataDir: string,
  analysisId: string,
  uniqueSuffix: string,
): string {
  assertAnalysisId(analysisId);
  assertTempSuffix(uniqueSuffix);
  return join(
    analysisDir(dataDir, analysisId),
    `${DOCUMENT_FILE_NAME}.${uniqueSuffix}${TEMP_FILE_SUFFIX}`,
  );
}